import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

export const START = "<!-- codebase-map:start -->";
export const END = "<!-- codebase-map:end -->";

const HEADER = `# Codebase map

Generated by [codebase-map](https://github.com/mogesjohnson/codebase-map). Edit freely outside the markers;
everything between them is regenerated on each run.

`;

/** Replace the region between markers, keeping everything outside. Creates the file if missing. */
export function mergeIntoFile(path: string, body: string): "created" | "updated" | "appended" {
  const block = `${START}\n${body.trim()}\n${END}`;
  if (!existsSync(path)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, HEADER + block + "\n");
    return "created";
  }
  const old = readFileSync(path, "utf8");
  const s = old.indexOf(START), e = old.indexOf(END, s + START.length);
  if (s >= 0 && e > s) {
    writeFileSync(path, old.slice(0, s) + block + old.slice(e + END.length));
    return "updated";
  }
  writeFileSync(path, old.replace(/\s*$/, "\n\n") + block + "\n");
  return "appended";
}
