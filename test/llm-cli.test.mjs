import { test } from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpTree } from "./helpers.mjs";
import { deadUrl, mockOllama } from "./ollama-mock.mjs";

const CLI = join(dirname(fileURLToPath(import.meta.url)), "..", "dist", "cli.js");
const TREE = {
  "core/index.ts": "/** Core parsing helpers. */\nexport function parse(s: string) { return s; }\n",
  "web/main.ts": "import { parse } from \"../core/index.js\";\nexport const app = parse(\"x\");\n",
};

/** Async spawn, so the in-process mock server can answer while the CLI runs. */
function run(args, env = {}) {
  return new Promise((res) => {
    execFile(process.execPath, [CLI, ...args], { encoding: "utf8", env: { ...process.env, ...env } },
      (err, stdout, stderr) => res({ status: err ? err.code : 0, stdout, stderr }));
  });
}
const mapOf = (root) => readFileSync(join(root, "docs", "CODEBASE_MAP.md"), "utf8");

test("--llm with a working Ollama writes labeled AI summaries and keeps static purposes", async () => {
  const mock = await mockOllama();
  try {
    const root = tmpTree(TREE);
    const r = await run([root, "--llm", "--llm-model", "tiny", "--ollama-url", mock.url]);
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /2 AI summaries/);
    const md = mapOf(root);
    assert.match(md, /AI summaries\*\* below are generated by a local LLM \(Ollama `tiny`\)/);
    assert.ok(md.includes("- AI summary (AI-generated, Ollama `tiny`): Summary of core."));
    assert.ok(md.includes("- AI summary (AI-generated, Ollama `tiny`): Summary of web."));
    assert.match(md, /\| `core` \| Core parsing helpers\. \|/);
    assert.equal(mock.requests.length, 2);
    assert.ok(mock.requests.every((q) => q.body.model === "tiny" && q.body.stream === false));
  } finally { await mock.close(); }
});

test("--llm honors OLLAMA_HOST and --llm-max-modules", async () => {
  const mock = await mockOllama();
  try {
    const root = tmpTree(TREE);
    const r = await run([root, "--llm", "--llm-max-modules=1"], { OLLAMA_HOST: mock.url.replace("http://", "") });
    assert.equal(r.status, 0, r.stderr);
    assert.equal(mock.requests.length, 1);
    assert.match(r.stdout, /1 module\(s\) keep only the static purpose/);
    assert.equal((mapOf(root).match(/- AI summary/g) || []).length, 1);
  } finally { await mock.close(); }
});

test("--llm with Ollama unreachable warns once, writes the static map, exits 0", async () => {
  const root = tmpTree(TREE);
  const r = await run([root, "--llm"], { OLLAMA_HOST: await deadUrl() });
  assert.equal(r.status, 0);
  assert.equal((r.stderr.match(/warning/g) || []).length, 1);
  assert.match(r.stderr, /cannot reach Ollama.*static map/);
  const md = mapOf(root);
  assert.ok(!md.includes("AI summary"));
  assert.match(md, /## Module dependencies/);
});

test("--llm with a timeout warns and still writes the static map", async () => {
  const mock = await mockOllama(() => {});
  try {
    const root = tmpTree(TREE);
    const r = await run([root, "--llm", "--ollama-url", mock.url, "--llm-timeout", "200"]);
    assert.equal(r.status, 0);
    assert.match(r.stderr, /did not answer within 200 ms/);
    assert.ok(!mapOf(root).includes("AI summary"));
  } finally { await mock.close(); }
});

test("--llm with a missing model (404) warns and still writes the static map", async () => {
  const mock = await mockOllama((body, res) => { res.writeHead(404).end(JSON.stringify({ error: "model not found" })); });
  try {
    const root = tmpTree(TREE);
    const r = await run([root, "--llm", "--ollama-url", mock.url, "--llm-model", "ghost"]);
    assert.equal(r.status, 0);
    assert.match(r.stderr, /model "ghost" not found.*ollama pull ghost/);
    assert.ok(!mapOf(root).includes("AI summary"));
  } finally { await mock.close(); }
});

test("without --llm the output is static and identical to an unreachable --llm run", async () => {
  const mock = await mockOllama();
  try {
    const a = tmpTree(TREE), b = tmpTree(TREE);
    await run([a], { OLLAMA_HOST: mock.url });
    await run([b, "--llm"], { OLLAMA_HOST: await deadUrl() });
    assert.equal(mock.requests.length, 0);
    assert.ok(!mapOf(a).includes("AI summary"));
    const norm = (root) => mapOf(root).split(root.split("/").pop()).join("REPO");
    assert.equal(norm(a), norm(b));
  } finally { await mock.close(); }
});
